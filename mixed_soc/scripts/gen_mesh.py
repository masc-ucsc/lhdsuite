#!/usr/bin/env python3
"""Emit the suite's one-packet-per-lane XY mesh in Pyrope from topology.py."""
from pathlib import Path
from topology import COLS, ROWS, TILES


def generate():
    n = len(TILES)
    flags = '(' + ', '.join(f'e{i}:U1' for i in reversed(range(n))) + ')'
    s = '''// Generated by mixed_soc/scripts/gen_mesh.py from topology.py.
// One packet in flight per lane, registered XY hops and round-robin admission.
// Lane 0 occupies the high packet slice, matching SV's unpacked-array boundary.
'''
    s += f'''pub mod mixed_mesh::[timecheck=false](`clock`:Clock, `reset`:U1, txv:U{n}, tx:U{136*n}, rxr:{flags}) -> (txr:U{n}@[], rxv:{flags}@[], rx:U{136*n}@[]) {{
  reg active:U1:[initial=0, reset_pin=`reset`, async=false]
  reg position:U5:[initial=0, reset_pin=`reset`, async=false]
  reg cursor:U5:[initial=0, reset_pin=`reset`, async=false]
  reg held:U136:[initial=0, reset_pin=`reset`, async=false]
  mut grant:U5 = {n}
  mut chosen:U136 = 0
  mut take:U1 = 0
  txr = 0
'''
    for scan in range(2):
        for i in range(n):
            a = (n-1-i)*136
            condition = f'{i} >= cursor' if scan == 0 else f'{i} < cursor'
            s += f'''  if reset == 0 and active == 0 and grant == {n} and {condition} and txv#[{i}] != 0 and tx#[{a+126}..={a+130}] < {n} {{
    grant = {i}
    chosen = tx#[{a}..={a+135}]
  }}
'''
    s += f'  if grant < {n} {{ wrap txr = 1 << grant }}\n'
    for i in range(n):
        s += f'''  rxv.e{i} = if active != 0 and position == {i} and held#[126..=130] == {i} {{ 1 }} else {{ 0 }}
  if position == {i} {{ take = rxr.e{i} }}
'''
    s += '  rx = (' + ', '.join(['held']*n) + ')#[..]\n'
    s += f'''  if reset != 0 {{
    active = 0
    cursor = 0
    position = 0
    held = 0
  }} elif active == 0 {{
    if grant < {n} {{
      active = 1
      position = grant
      held = chosen
      held#[131..=135] = grant
      cursor = if grant == {n-1} {{ 0 }} else {{ grant + 1 }}
    }}
  }} elif position == held#[126..=130] {{
    if take != 0 {{ active = 0 }}
  }} else {{
    const target = held#[126..=130]
'''
    for coord, value in [('py', 'position'), ('ty', 'target')]:
        expr = ' '.join(('if' if row == ROWS-1 else 'elif') + f' {value} >= {row*COLS} {{ {row} }}' for row in reversed(range(1,ROWS)))
        s += f'    const {coord} = {expr} else {{ 0 }}\n'
    s += f'''    const px = position - ({COLS} * py)
    const target_x = target - ({COLS} * ty)
    if target_x < px {{ wrap position -= 1 }}
    elif target_x > px {{ wrap position += 1 }}
    elif ty < py {{ wrap position -= {COLS} }}
    else {{ wrap position += {COLS} }}
  }}
}}
'''
    return s


if __name__ == '__main__':
    (Path(__file__).resolve().parent.parent/'pyrope/mixed_mesh.prp').write_text(generate())
