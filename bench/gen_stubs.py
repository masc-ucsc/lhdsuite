#!/usr/bin/env python3
"""Derive the DiffExt* synthesis sink models from the DummyDPICWrapper_* sources.

The SV wrappers instantiate their DPI cell only under `ifdef DUMMY`, which is
off for synthesis, so under -DSYNTHESIS the wrapper body is EMPTY. The Pyrope
snapshot has no preprocessor and kept the instantiation unconditionally, so the
translated tree references ~20 modules that do not exist in it. Rather than edit
the imported design, supply a sink model per cell: same port names, no outputs,
empty body -- which is what the wrapper compiles to in Verilog anyway.

Everything here is DERIVED from the wrappers, so a regenerated XiangShan
snapshot picks up new/renamed cells and changed widths automatically.

usage: gen_stubs.py <pyrope_dir> <out_dir>
"""
import glob
import os
import re
import sys


def stub_of(path):
    txt = open(path).read()
    m = re.search(r'import\("(DiffExt\w+)\.', txt)
    if not m:
        return None
    cell = m.group(1)

    # The one instantiation line: `mut dpic = <cell>::[name=dpic](clock = ...,
    # enable = ..., io = (...)#[0..=N])`. The LAST bit-slice on that line is the
    # packed `io` operand, so its width is N+1.
    line = next((l for l in txt.splitlines() if re.search(r'=\s*%s::' % cell, l)), None)
    if line is None:
        return None
    args = re.findall(r'(\w+)\s*=', line.split("](", 1)[1]) if "](" in line else []
    slices = re.findall(r'#\[0\.\.=(\d+)\]', line)
    width = int(slices[-1]) + 1 if slices else None
    return cell, width, [a for a in dict.fromkeys(args) if a in ("clock", "enable", "io")]


def main():
    src, out = sys.argv[1], sys.argv[2]
    os.makedirs(out, exist_ok=True)
    seen = {}
    for f in sorted(glob.glob(os.path.join(src, "DummyDPICWrapper_*.prp"))):
        got = stub_of(f)
        if not got:
            print("SKIP (no DiffExt import): %s" % os.path.basename(f), file=sys.stderr)
            continue
        cell, width, args = got
        if width is None:
            print("SKIP (no io width): %s" % cell, file=sys.stderr)
            continue
        if cell in seen and seen[cell] != width:
            sys.exit("FAIL: %s wanted with two widths: %d and %d" % (cell, seen[cell], width))
        seen[cell] = width

        ports = ", ".join(
            {"clock": "clock:u1", "enable": "enable:u1", "io": "io:u%d" % width}[a] for a in args
        )
        body = (
            "// Synthesis sink model for the `%s` DPI cell.\n"
            "//\n"
            "// GENERATED by bench/gen_stubs.py from DummyDPICWrapper_*.prp -- do not edit,\n"
            "// and do not commit. The SV wrapper instantiates this cell only under\n"
            "// `ifdef DUMMY`, so under -DSYNTHESIS its body is empty; this reproduces that\n"
            "// for the Pyrope snapshot, which lost the ifdef in translation.\n"
            "//\n"
            "// No outputs, empty body: the instance is dead and every backend drops it,\n"
            "// which is exactly what the Verilog side compiles to.\n"
            "pub mod %s::[timecheck=false](%s) -> () {\n}\n" % (cell, cell, ports)
        )
        open(os.path.join(out, cell + ".prp"), "w").write(body)

    print("generated %d stub(s) into %s" % (len(seen), out))
    for cell, width in sorted(seen.items()):
        print("  %-40s io:u%d" % (cell, width))


main()
