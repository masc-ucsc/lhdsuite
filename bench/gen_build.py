#!/usr/bin/env python3
"""Turn an `lhd scan` result into a real build graph (Makefile + BUILD.bazel).

`lhd scan` exists for exactly this ("For depfile writers and BUILD generators
(gazelle-style)" -- see `lhd scan --help`): it parses every .prp and reports the
import strings, which is the whole dependency picture a build system needs.

The generated Makefile is the interesting artifact: one rule per Pyrope file,
prerequisites = that file's DIRECT imports, so `make -j` derives the parallel
schedule itself instead of the bench hand-rolling topological waves.

A rule's PREREQUISITES and the `lhd` INPUT LIST are deliberately not the same
set, because the two IR emissions differ in closure:

  * `--emit-dir lg:DIR` is TRANSITIVELY CLOSED -- lg_foo holds foo's graphs plus
    every graph foo imported. Hence lg_<top> is already the complete design
    library and there is no final link step.
  * `--emit-dir ln:DIR` is NOT closed -- it publishes only the unit's own trees.

So prerequisites are each file's DIRECT imports (the true build graph, which is
what `make -j` should schedule on and what a BUILD generator should emit), while
the command line passes the file's full transitive closure -- necessary because
any dependency that turns out to be type/constant-only produces no lgraph, comes
in as `ln:`, and then does not carry its own imports. `vpu_defs_pkg` is exactly
that case. Passing the closure costs nothing measurable once dependencies arrive
pre-lowered (core_top: 5 direct inputs 37.5s vs 89 closure inputs 36.0s).

A dependency is passed in its PRE-LOWERED `lg:` form when that unit produced
graphs, and as `ln:` otherwise. This matters a lot: handing a unit to a dependent
as `ln:` re-elaborates it from the AST on every load -- for a `comb` unit that
costs the same as recompiling it from source -- while `lg:` reuses the lowered
netlist. Which form applies is only knowable after the dependency has been
built, so the recipe resolves it at run time rather than the generator guessing.

Usage:
  gen_build.py SCAN_JSON --top TOP --mk build.mk --bazel BUILD.bazel

Writes a `key value` summary to stdout for the caller to turn into METRICs.
"""

import argparse
import ast
import json
import os
import sys


def stem(path):
    """minion/pyrope/foo.prp -> foo (the module/import name)."""
    return os.path.basename(path)[:-4]


def load_scan(path):
    """scan.json -> {stem: (src_path, [direct import stems])}.

    Import strings are `file.symbol` or bare `file`; only the leading file part
    names a compilation unit. Imports that resolve outside the scanned set are
    dropped: `lhd`'s own sibling discovery handles those, and a build rule
    cannot depend on a file the scan never saw.
    """
    entries = json.load(open(path))["scan"]
    src = {stem(e["file"]): e["file"] for e in entries}
    deps = {}
    for e in entries:
        want = {i.split(".")[0] for i in e["imports"]}
        deps[stem(e["file"])] = sorted(w for w in want if w in src and w != stem(e["file"]))
    return src, deps


def cone(top, deps):
    """Every unit reachable from `top` -- the only files a --top build needs."""
    seen, stack = set(), [top]
    while stack:
        u = stack.pop()
        if u in seen:
            continue
        seen.add(u)
        stack.extend(deps[u])
    return seen


def closures(units, deps):
    """{unit: transitive imports}, memoized. The `lhd` input list, not the graph."""
    memo = {}

    def walk(u):
        if u in memo:
            return memo[u]
        memo[u] = set()  # guards self-reference; real cycles die in levels()
        acc = set()
        for d in deps[u]:
            acc.add(d)
            acc |= walk(d)
        memo[u] = acc
        return acc

    return {u: sorted(walk(u)) for u in units}


def levels(units, deps):
    """Topological depth per unit; also the cycle check."""
    lvl, state = {}, {}

    def visit(u):
        if state.get(u) == "done":
            return lvl[u]
        if state.get(u) == "open":
            sys.exit(f"FAIL: import cycle through '{u}' -- not a buildable graph")
        state[u] = "open"
        lvl[u] = 1 + max([visit(d) for d in deps[u]], default=-1)
        state[u] = "done"
        return lvl[u]

    for u in units:
        visit(u)
    return lvl


MK_HEADER = """\
# GENERATED by bench/gen_build.py from `lhd scan` -- do not edit.
#
# One rule per Pyrope file; prerequisites are that file's DIRECT imports.
# `make -j` derives the parallel schedule from this graph, so the bench does
# not hand-roll topological waves.
#
# Dependencies ride in as `ln:` — that is what resolves a Pyrope `import`
# (`lhd compile --help`: "positional ln:DIR supplies pre-elaborated imports,
# lg:DIR pre-compiled libraries"). Passing the `lg:` form instead does NOT
# satisfy an import; the compile then falls back to sibling .prp discovery and
# silently RE-COMPILES every import from source, which is the opposite of what
# this bench is meant to demonstrate. With `ln:` supplied, the front-end parses
# only the named source and the emission stays a strict subset.
#
# Recipes deliberately do NOT clean their own emission directories first. A
# rebuild re-emits over the previous run's `ln_`/`lg_` dirs, so re-emission has
# to be idempotent — if it ever stops being, this bench must fail rather than
# hide it behind an rm -rf.
#
# `--emit-dir lg:` is transitively closed, so lg_<top> is already the complete
# design library and needs no final link step.
#
# top: {top}
# units: {n} of {total} scanned files ({pruned} pruned as outside the top's cone)
# critical path: {depth} levels

LHD ?= lhd

.SUFFIXES:
.PHONY: all
all: out_lg

stamp:
\t@mkdir -p stamp
"""

MK_RULE = """
# {unit} (level {lvl}){dep_note}
# prerequisites: direct imports. inputs below: full closure -- ln: is not closed.
stamp/{unit}.ok: {src}{dep_stamps} | stamp
\t@$(LHD) compile {src} {ir_ins} \\
\t   --emit-dir ln:ln_{unit} --emit-dir lg:lg_{unit} --workdir cw_{unit} \\
\t   >u_{unit}.log 2>&1 \\
\t   || {{ echo "FAIL: compiling {unit}" >&2; tail -20 u_{unit}.log >&2; exit 1; }}
\t@touch $@
"""

MK_LEAF_RULE = """
# {unit} (level 0, no imports)
stamp/{unit}.ok: {src} | stamp
\t@$(LHD) compile {src} \\
\t   --emit-dir ln:ln_{unit} --emit-dir lg:lg_{unit} --workdir cw_{unit} \\
\t   >u_{unit}.log 2>&1 \\
\t   || {{ echo "FAIL: compiling {unit}" >&2; tail -20 u_{unit}.log >&2; exit 1; }}
\t@touch $@
"""

MK_FOOTER = """
# lg_{top} is already the whole-design library (lg: emission is transitively
# closed), so publishing it is a rename, not a link step.
out_lg: stamp/{top}.ok
\t@rm -rf out_lg && ln -s lg_{top} out_lg
"""


def emit_make(path, top, units, src, deps, clo, lvl, total):
    order = sorted(units)
    out = [MK_HEADER.format(top=top, n=len(units), total=total,
                            pruned=total - len(units), depth=max(lvl.values()) + 1)]
    for u in order:
        if deps[u]:
            out.append(MK_RULE.format(
                unit=u, src=src[u], lvl=lvl[u],
                dep_note="; %d direct imports, %d in closure" % (len(deps[u]), len(clo[u])),
                dep_stamps="".join(" \\\n    stamp/%s.ok" % d for d in deps[u]),
                ir_ins=" ".join("ln:ln_%s" % d for d in clo[u])))
        else:
            out.append(MK_LEAF_RULE.format(unit=u, src=src[u]))
    out.append(MK_FOOTER.format(top=top))
    open(path, "w").write("".join(out))


BZL_HEADER = '''\
# GENERATED by bench/gen_build.py from `lhd scan` -- do not edit.
#
# ILLUSTRATIVE ARTIFACT. This file is emitted and syntax-checked by the
# compile_pyrope_parallel bench to show what gazelle-style BUILD generation off
# `lhd scan` looks like; the bench itself builds with the generated Makefile and
# never executes this. Running it would need a `prp_library` rule (whose action
# is the same `lhd compile` the Makefile recipes run, with the lg:/ln: dirs
# carried on a provider) -- that rule does not exist in this repo yet.
#
# The point is that the dependency graph needs nothing but `lhd scan`: deps are
# each file's DIRECT imports, because `--emit-dir lg:` is transitively closed.
#
# top: {top} -- {n} of {total} scanned files

load("//bench:prp.bzl", "prp_library")

'''

BZL_RULE = '''prp_library(
    name = "{unit}",
    src = "{src}",
    deps = [{deps}],
)

'''


def emit_bazel(path, top, units, src, deps, total):
    out = [BZL_HEADER.format(top=top, n=len(units), total=total)]
    for u in sorted(units):
        d = ", ".join('":%s"' % x for x in deps[u])
        out.append(BZL_RULE.format(unit=u, src=os.path.basename(src[u]), deps=d))
    text = "".join(out)
    # Starlark is a Python subset -- ast.parse is a real syntax check, so a
    # malformed emission fails the bench instead of shipping a broken artifact.
    try:
        ast.parse(text)
    except SyntaxError as e:
        sys.exit("FAIL: generated BUILD.bazel is not syntactically valid: %s" % e)
    open(path, "w").write(text)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("scan_json")
    ap.add_argument("--top", required=True)
    ap.add_argument("--mk", required=True)
    ap.add_argument("--bazel")
    a = ap.parse_args()

    src, deps = load_scan(a.scan_json)
    if a.top not in src:
        sys.exit("FAIL: --top '%s' is not among the %d scanned files" % (a.top, len(src)))

    units = cone(a.top, deps)
    lvl = levels(units, deps)
    clo = closures(units, deps)
    emit_make(a.mk, a.top, units, src, deps, clo, lvl, len(src))
    if a.bazel:
        emit_bazel(a.bazel, a.top, units, src, deps, len(src))

    print("units %d" % len(units))
    print("pruned %d" % (len(src) - len(units)))
    print("depth %d" % (max(lvl.values()) + 1))
    print("widest %d" % max(sum(1 for u in units if lvl[u] == k)
                            for k in set(lvl.values())))


if __name__ == "__main__":
    main()
